import cv2
import numpy as np
import glob, os, random
from PIL import Image

random.seed(42)

VARIANTS_PER_DONOR = 4       # cuántas copias sintéticas generar por cada manchón/cluster fuente
AREA_PERCENTILE = 85         # boxes por encima de este percentil de área = "manchón grande"
MIN_CLUSTER_BOXES = 5        # tiles con esta cantidad de boxes o más = candidato a "fila densa"
TILE_W, TILE_H = 1024, 1024

def load_yolo_labels(label_path):
    boxes = []
    if not os.path.exists(label_path) or os.path.getsize(label_path) == 0:
        return boxes
    with open(label_path) as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) == 5:
                _, cx, cy, w, h = map(float, parts)
                boxes.append((cx, cy, w, h))
    return boxes

def yolo_to_px(box, tile_w=TILE_W, tile_h=TILE_H):
    cx, cy, w, h = box
    x1 = (cx - w/2) * tile_w
    y1 = (cy - h/2) * tile_h
    x2 = (cx + w/2) * tile_w
    y2 = (cy + h/2) * tile_h
    return int(x1), int(y1), int(x2), int(y2)

def px_to_yolo(x1, y1, x2, y2, tile_w=TILE_W, tile_h=TILE_H):
    cx = ((x1 + x2) / 2) / tile_w
    cy = ((y1 + y2) / 2) / tile_h
    w = (x2 - x1) / tile_w
    h = (y2 - y1) / tile_h
    return cx, cy, w, h

def extract_mask_grabcut(img_bgr, x1, y1, x2, y2, margin=15):
    h_img, w_img = img_bgr.shape[:2]
    mx1, my1 = max(0, x1 - margin), max(0, y1 - margin)
    mx2, my2 = min(w_img, x2 + margin), min(h_img, y2 + margin)
    crop = img_bgr[my1:my2, mx1:mx2].copy()
    if crop.shape[0] < 10 or crop.shape[1] < 10:
        return None, None
    rect = (margin, margin, max(1, (x2-x1)), max(1, (y2-y1)))
    mask = np.zeros(crop.shape[:2], np.uint8)
    bgd, fgd = np.zeros((1,65), np.float64), np.zeros((1,65), np.float64)
    try:
        cv2.grabCut(crop, mask, rect, bgd, fgd, 5, cv2.GC_INIT_WITH_RECT)
    except cv2.error:
        return None, None
    fg_mask = np.where((mask==cv2.GC_FGD)|(mask==cv2.GC_PR_FGD), 255, 0).astype(np.uint8)
    return crop, fg_mask

