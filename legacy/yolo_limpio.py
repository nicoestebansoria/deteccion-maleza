TILE_SIZE = 1024
OVERLAP = 200          # px de solape entre tiles vecinos
STEP = TILE_SIZE - OVERLAP
NODATA_THRESHOLD = 0.3  # si un tile tiene >30% de píxeles negros/vacíos, se descarta

tile_metadata = []  # acá guardamos la georreferencia de cada tile, la vamos a necesitar después

with rasterio.open(ortho_path) as src:
    width, height = src.width, src.height

    tile_id = 0
    for top in range(0, height, STEP):
        for left in range(0, width, STEP):
            w = min(TILE_SIZE, width - left)
            h = min(TILE_SIZE, height - top)
            if w <= 0 or h <= 0:
                continue

            window = Window(left, top, w, h)
            tile = src.read([1, 2, 3], window=window)  # bandas R, G, B
            tile = np.moveaxis(tile, 0, -1)  # (bands, h, w) -> (h, w, bands)

            # descartar tiles mayormente vacíos (bordes irregulares del ortomosaico)
            black_pixels = np.all(tile == 0, axis=-1).sum()
            if black_pixels / (tile.shape[0] * tile.shape[1]) > NODATA_THRESHOLD:
                continue

            # pad si el tile quedó más chico (borde del raster)
            if tile.shape[0] != TILE_SIZE or tile.shape[1] != TILE_SIZE:
                padded = np.zeros((TILE_SIZE, TILE_SIZE, 3), dtype=tile.dtype)
                padded[:tile.shape[0], :tile.shape[1], :] = tile
                tile = padded

            tile_filename = f"tile_{tile_id:05d}.jpg"
            Image.fromarray(tile).save(os.path.join(output_dir, tile_filename), quality=95)

            # guardamos la transformación geográfica de este tile (para georreferenciar detecciones después)
            tile_transform = src.window_transform(window)
            tile_metadata.append({
                "tile_id": tile_id,
                "filename": tile_filename,
                "window_left": left,
                "window_top": top,
                "window_width": w,
                "window_height": h,
                "transform": list(tile_transform)[:6],
                "crs": str(src.crs)
            })

            tile_id += 1

