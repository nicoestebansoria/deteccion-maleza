def image_to_base64(path):
    with open(path, "rb") as f:
        return "data:image/jpeg;base64," + base64.b64encode(f.read()).decode("utf-8")

def yolo_txt_to_widget_bboxes(label_path, tile_w=TILE_W, tile_h=TILE_H):
    bboxes = []
    if not os.path.exists(label_path) or os.path.getsize(label_path) == 0:
        return bboxes
    with open(label_path) as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) == 5:
                _, cx, cy, w, h = map(float, parts)
                x = (cx - w/2) * tile_w
                y = (cy - h/2) * tile_h
                bboxes.append({"x": x, "y": y, "width": w * tile_w, "height": h * tile_h, "label": "maleza"})
    return bboxes

def yolo_from_bboxes(bboxes):
    lines = []
    for b in bboxes:
        x, y, w, h = b["x"], b["y"], b["width"], b["height"]
        cx, cy = (x + w/2) / TILE_W, (y + h/2) / TILE_H
        nw, nh = w / TILE_W, h / TILE_H
        lines.append(f"0 {cx:.6f} {cy:.6f} {nw:.6f} {nh:.6f}")
    return lines

