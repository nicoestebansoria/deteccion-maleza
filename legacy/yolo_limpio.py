#@title 12. Poligonización de detecciones (GrabCut)
import cv2, math
import numpy as np
from rasterio.windows import from_bounds
from shapely.geometry import Polygon

MARGIN_MIN_M = 0.15
MARGIN_RATIO = 0.35   # margen = 35% de la diagonal del box, con piso de MARGIN_MIN_M
GRABCUT_ITER = 5
MIN_BLOB_AREA_PX = 15

polygons_data = []
failed_count = 0

with rasterio.open(ortho_path) as src:
    res_x, res_y = src.res  # tamaño de píxel en metros

    for idx, row in gdf_dedup.iterrows():
        box_w_m = row["box_maxx"] - row["box_minx"]
        box_h_m = row["box_maxy"] - row["box_miny"]
        diagonal_m = math.hypot(box_w_m, box_h_m)
        margin_m = max(MARGIN_MIN_M, diagonal_m * MARGIN_RATIO)

        window = from_bounds(
            row["box_minx"] - margin_m, row["box_miny"] - margin_m,
            row["box_maxx"] + margin_m, row["box_maxy"] + margin_m,
            transform=src.transform
        )
        window_transform = src.window_transform(window)

        crop = src.read([1, 2, 3], window=window)
        if crop.shape[1] < 10 or crop.shape[2] < 10:
            failed_count += 1
            continue

        img_bgr = np.transpose(crop, (1, 2, 0))[:, :, ::-1].astype(np.uint8).copy()
        h, w = img_bgr.shape[:2]

        margin_px_x = int(margin_m / res_x)
        margin_px_y = int(margin_m / res_y)
        rect = (
            max(0, margin_px_x), max(0, margin_px_y),
            max(1, w - 2 * margin_px_x), max(1, h - 2 * margin_px_y)
        )

        mask = np.zeros((h, w), np.uint8)
        bgd_model = np.zeros((1, 65), np.float64)
        fgd_model = np.zeros((1, 65), np.float64)

        try:
            cv2.grabCut(img_bgr, mask, rect, bgd_model, fgd_model, GRABCUT_ITER, cv2.GC_INIT_WITH_RECT)
        except cv2.error:
            failed_count += 1
            continue

        fg_mask = np.where((mask == cv2.GC_FGD) | (mask == cv2.GC_PR_FGD), 1, 0).astype(np.uint8)

        contours, _ = cv2.findContours(fg_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        if not contours:
            failed_count += 1
            continue

        largest = max(contours, key=cv2.contourArea)
        if cv2.contourArea(largest) < MIN_BLOB_AREA_PX:
            failed_count += 1
            continue

        largest = cv2.approxPolyDP(largest, 0.5, True)

        a, b_, c, d, e, f = (window_transform.a, window_transform.b, window_transform.c,
                              window_transform.d, window_transform.e, window_transform.f)
        pixel_coords = [(pt[0][0], pt[0][1]) for pt in largest]
        geo_coords = [(a * px + b_ * py + c, d * px + e * py + f) for px, py in pixel_coords]

        if len(geo_coords) < 3:
            failed_count += 1
            continue

        poly = Polygon(geo_coords)
        if not poly.is_valid or poly.area == 0:
            failed_count += 1
            continue

        polygons_data.append({
            "geometry": poly,
            "confidence": row["confidence"],
            "tile_source": row["tile_source"],
            "area_m2": poly.area
        })

print(f"Polígonos generados: {len(polygons_data)} de {len(gdf_dedup)} detecciones")
print(f"Fallidos: {failed_count}")

gdf_polygons = gpd.GeoDataFrame(polygons_data, crs=gdf_dedup.crs)

