import glob, os, json
import rasterio
from rasterio.transform import Affine
import geopandas as gpd
from shapely.geometry import Point
from ultralytics import YOLO

# cargar el mejor modelo entrenado
model = YOLO(f"{base_dir}/runs/weed_detection_v1/weights/best.pt")

# cargar la georreferencia de cada tile
with open(f"{tiles_dir}/tiles_metadata.json") as f:
    tiles_meta = {m["filename"]: m for m in json.load(f)}

CONF_THRESHOLD = 0.35  # subido del default 0.25 para reducir falsos positivos, dado el precision bajo

all_detections = []

for tile_path in sorted(glob.glob(f"{tiles_dir}/*.jpg")):
    tile_filename = os.path.basename(tile_path)
    if tile_filename not in tiles_meta:
        continue

    meta = tiles_meta[tile_filename]
    tile_transform = Affine(*meta["transform"])
    crs = meta["crs"]

    results = model.predict(tile_path, conf=CONF_THRESHOLD, verbose=False)

    for r in results:
        for box_data in r.boxes:
            x1, y1, x2, y2 = box_data.xyxy[0].tolist()
            confidence = float(box_data.conf[0])
            cx_px, cy_px = (x1 + x2) / 2, (y1 + y2) / 2

            # centro geo (para dedup, igual que antes)
            geo_x, geo_y = tile_transform * (cx_px, cy_px)

            # las 4 esquinas del box, transformadas a coordenadas geo
            corners_px = [(x1, y1), (x2, y1), (x2, y2), (x1, y2)]
            corners_geo = [tile_transform * c for c in corners_px]
            geo_xs = [c[0] for c in corners_geo]
            geo_ys = [c[1] for c in corners_geo]

            all_detections.append({
                "geometry": Point(geo_x, geo_y),
                "confidence": confidence,
                "tile_source": tile_filename,
                "crs": crs,
                "box_minx": min(geo_xs), "box_maxx": max(geo_xs),
                "box_miny": min(geo_ys), "box_maxy": max(geo_ys),
            })

gdf_raw = gpd.GeoDataFrame(all_detections, crs=all_detections[0]["crs"] if all_detections else None)
print(f"Detecciones crudas: {len(gdf_raw)}")

